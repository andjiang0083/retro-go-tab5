/* ============================================================================
 * Tab5 虚拟手柄键位表 —— 单一数据源
 * ----------------------------------------------------------------------------
 * 为什么单独放一个文件：这张表同时被三方使用
 *   1. 触摸命中判定（rg_input.c）
 *   2. 可视层绘制（rg_touch_overlay.c：标签/边框/透明度的位置都从这张表来）
 *   3. PC 预览（SDL2 宿主构建要按同一套布局渲染，否则"预览"没意义）
 * 抄成两份必然漂移 —— 表现就是"画的和点的不是一回事"。
 *
 * 坐标是**逻辑横向空间**（1280x720，即用户实际看到的画面），(x,y) = 命中区中心。
 *
 * 硬约束：命中区**不得压到游戏画面**。按 3x 整数缩放（240x160 -> 720x480 居中）计算，
 * 游戏区占 x[280,1000) y[120,600)，四周空白 margin 为：左 280 / 右 280 / 上 120 / 下 120。
 * 本表所有命中区都留了 >=8px 间隙，只落在 margin 内。
 *
 * ⚠ 因此游戏缩放模式必须是 ZOOM(custom_zoom=3)：FULL 会拉满 1280x720（零 margin），
 *   FIT 会变成 1080x720（上下零 margin）——这两种模式下按键都会压到画面。
 * （launcher 菜单是全屏 UI，那时按键压到菜单是正常的、也是必需的。）
 * ==========================================================================*/

