/* ----------------------------------------------------------------------------
 * L/R 之间那颗「X/Y ↔ L/R 调换」按钮（2026-09-29 用户需求）
 * ----------------------------------------------------------------------------
 * 需求原话："增加一个 lr 和 yx 调换的按钮，可以让用户将 lr 切换到更容易点击的地方"
 * （格斗游戏里 L/R 经常要用，但肩键位不好按 —— 换到拇指够得着的菱形位上就顺了）。
 *
 * 它**不是游戏按键**：不注入任何 RG_KEY_*，只切映射（X↔R、Y↔L，规则见
 * rg_touch_overlay.h 的 rg_touch_swap_key()）。默认菱形上是 X/Y，点一下变成 R/L，
 * 肩键位跟着变 X/Y；标签显示"菱形上现在是哪一对"（X/Y ↔ L/R）。
 *
 * 几何：与 L/R 同排（y=545）。L 占 x 50~230、R 占 x 490~670，中间 260px 空着，
 * 取 180 宽居中（360）→ 两侧各留 40px，视觉上像"这一排的第三个键"。
 * 命中矩形另外外扩一点（见 rg_touch_overlay.c 的 RG_OVERLAY_SWAP_PAD）。 */
#define RG_TAB5_SWAP_X  360
#define RG_TAB5_SWAP_Y  545
#define RG_TAB5_SWAP_W  180
#define RG_TAB5_SWAP_H  84

